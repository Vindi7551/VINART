/**
 * 动态组装 system prompt。
 * 美术指导单独使用时调用；配对模式下由 concepting 合并 prompt。
 */
export function buildArtDirectorContext(brief: CreativeBrief): string {
  return [
    '创意简报：',
    `  产品：${brief.productName}`,
    `  描述：${brief.productDescription}`,
    `  使用场景：${brief.useCase}`,
    `  目标受众：${brief.targetAudience}`,
    `  核心信息：${brief.keyMessage}`,
    `  品牌调性：${brief.brandPersonality}`,
    `  品牌语气：${brief.brandVoice}`,
    `  调性关键词：${brief.toneKeywords.join('、')}`,
    `  视觉风格：${brief.visualStyle}`,
    `  情绪氛围：${brief.mood}`,
    `  色彩方向：${brief.colorDirection}`,
    `  画布尺寸：${brief.canvas.width}×${brief.canvas.height}`,
    brief.referenceImageNotes ? `  参考图：${brief.referenceImageNotes}` : '',
    brief.mustInclude ? `  必须包含：${brief.mustInclude.join('、')}` : '',
    brief.mustAvoid ? `  必须避免：${brief.mustAvoid.join('、')}` : '',
  ].filter(Boolean).join('\n');
}
