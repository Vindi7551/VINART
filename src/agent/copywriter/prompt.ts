/**
 * 动态组装上下文。
 */
export function buildCopywriterContext(brief: CreativeBrief): string {
  return [
    '创意简报：',
    `  产品：${brief.productName}`,
    `  描述：${brief.productDescription}`,
    `  目标受众：${brief.targetAudience}`,
    `  核心信息：${brief.keyMessage}`,
    `  品牌调性：${brief.brandPersonality}`,
    `  品牌语气：${brief.brandVoice}`,
    `  调性关键词：${brief.toneKeywords.join('、')}`,
    `  情绪氛围：${brief.mood}`,
    brief.mustInclude ? `  必须包含：${brief.mustInclude.join('、')}` : '',
    brief.mustAvoid ? `  必须避免：${brief.mustAvoid.join('、')}` : '',
  ].filter(Boolean).join('\n');
}
