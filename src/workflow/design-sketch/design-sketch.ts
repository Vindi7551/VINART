/**
 * ═══════════════════════════════════════════════════════════════════════
 * DesignSketch —— 设计草图契约
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ## ⚠️ 先钉死两个词——之前所有混乱都出在这里
 *
 * | 词 | 指什么 | 在哪 |
 * |---|---|---|
 * | **位置尺寸**（`rect`） | 一个元素放在哪、占多大 | **每个节点都有** |
 * | **框**（`shape`） | 一个包住别的东西的**形状** | 它是**独立的节点**，不是属性 |
 *
 * 「框住图片」**不是数据结构**，而是**两个独立节点位置重叠**的视觉结果。
 * 同理「底板」——它也是一个形状节点，只是填了色而已。
 *
 * ## 一个设计只有三样东西
 *
 * ```
 *   图  ·  文字  ·  形状
 * ```
 *
 * | 类 | 是什么 | 视角 |
 * |---|---|---|
 * | **图** | 照片、场景、商品图、图标 | 主图 / 次级图 |
 * | **文字** | 要出现在画面上的文案 | 主要文字 / 次要文字 |
 * | **形状** | 框 · 底板 · 分区，**三合一** | 描边不填充 = 框；填充不描边 = 底板；都有 = 实心底加一圈边 |
 *
 * **主次靠尺寸和位置自然表达**——数据里不写"这是主图"。
 * 主图自然就大、就居中；次级图自然就小、就在边上。
 * （样式如颜色、线宽归 `design-appearance.json`；契约只说"什么形状、放在哪"。）
 *
 * ## 这份契约只回答一个问题
 *
 * ```
 *   什么放在哪、多大
 * ```
 *
 * 判据只有一条：**改它会不会让别的东西挪位置？**
 *
 * | 会 → 写这里 | 不会 → 它属于别的文件 |
 * |---|---|
 * | 位置 / 尺寸 / 字号 / 形状 / 旋转 | 颜色描边 → `design-appearance.json` |
 * |  | 光影材质 → 生图提示词 |
 * |  | 素材怎么生成 → `asset-order.json` |
 *
 * ## 网格：12 × 12，但**不进数据**
 *
 * 网格是**画在草图上给人（和 VLM）读数的辅助线**，不是数据的字段。
 * 之所以选 12 列 × 12 行：它能被 2 / 3 / 4 / 6 整除，
 * 元素的边缘与等分都好落在格线上。
 *
 * ⚠️ 它是**参照，不是约束**——元素可以贴格，也可以**故意偏离**来制造视觉张力。
 * 所以校验器**不会**因为"没对齐网格"报任何错。
 *
 * ## 旋转：视觉变换，不参与布局
 *
 * `transform`（旋转）只是最后一步把画面转一下。**`rect` 永远是旋转前的矩形**——
 * 所以对齐、间距、网格全部继续按 `rect` 算，不会因为旋转而失去意义。
 *
 * 为什么不让 `rect` 表示"转完之后的范围"：一个转过的矩形**没有「边」**，
 * 只有四个角点——"左边缘对齐"这类说法本身就退化了。
 * 而且 CSS 天然就是「先布局、后 transform」，照这个约定实现零成本。
 *
 * 代价：「数据上对齐」与「看起来对齐」会有偏差 → 靠**看图**发现（人审 / VLM）。
 *
 * ## 当前**刻意不含**什么
 *
 * 这些不是遗漏，是**暂缓**——骨架先跑通，再逐个加回来：
 *
 * | 缺什么 | 影响 | 加回时的原则 |
 * |---|---|---|
 * | **更复杂的组合形状** | 目前只有拱门一种"组合" | **不要引入布尔运算**；只加"有名字的预设形状" |
 * | **分组 / 复制** | "三张卡"要手写三遍 | 属结构，与内容正交 |
 * | **对齐关系**（声明式）| 现在全靠手算坐标 | 属关系，与元素正交 |
 * | **效果层**（压暗 / 暗角 / 阴影）| —— | **不该回来**：归生图提示词 |
 * | **有机形状**（飘带、流体）| 用形状逼近会很丑 | **不该回来**：它们归**素材图**，不是框 |
 */

// ══════════════════════════════════════════════════════════════════════
// 画布
// ══════════════════════════════════════════════════════════════════════

/**
 * 画布尺寸（px）。
 *
 * ⚠️ 这是契约里**唯一的绝对像素**——因为画布尺寸本身就是像素（如 2000×2000）。
 * 节点的一切位置与尺寸都用 0–1 比例，与它解耦。
 *
 * （渲染器到处都要用它，所以单独导出，而不是内联在 `DesignSketch` 里。）
 */
export interface Canvas {
  width: number;
  height: number;
}

// ══════════════════════════════════════════════════════════════════════
// 位置尺寸
// ══════════════════════════════════════════════════════════════════════

/**
 * **位置尺寸** —— 每个节点都有，一律 0–1 比例。
 *
 * ⚠️ 它**相对谁**取决于所在层级：
 * - 顶层节点 → 相对**画布**
 * - 组内子节点 → 相对**它的组**（如果将来加嵌套）
 *
 * `x:0.5` 在顶层是"画布中线"，在组内是"组的中线"——**含义不同，值相同**。
 */
export interface Rect {
  /** 左上角 x（0–1） */
  x: number;
  /** 左上角 y（0–1） */
  y: number;
  /** 宽（0–1） */
  w: number;
  /** 高（0–1） */
  h: number;
}

// ══════════════════════════════════════════════════════════════════════
// 形状
// ══════════════════════════════════════════════════════════════════════

/**
 * 形状的种类。
 *
 * ## 为什么是「枚举」而不是「任意顶点」
 *
 * 因为**模型选一个名字，远比算一串顶点坐标稳**——这正是项目已验证的
 * 那条原则：「把『给数值』变成『选位置』」。
 * 一个"上圆下方"的拱门，实现上是一段**写死的几何**，一次实现永远复用。
 *
 * 而且任意顶点会让**对齐、网格、间距全部失效**——形状的包围盒不再有意义。
 *
 * ## 朝向怎么办
 *
 * **不设朝向参数，交给 `rotate`**。尖朝上的三角形转 180° 就是尖朝下。
 *
 * ## 加新形状的标准
 *
 * 只加**有名字、会复用**的。一次性的怪异形状（飘带、水花）应该做成**素材图**，
 * 而不是逼近成多边形——那既不好看，也不可复用。
 */
export const SHAPES = ['rect', 'ellipse', 'arch', 'triangle'] as const;
export type Shape = (typeof SHAPES)[number];

// ══════════════════════════════════════════════════════════════════════
// 三类节点
// ══════════════════════════════════════════════════════════════════════

/**
 * 视觉变换 —— 只作用于最终画面，**不参与任何布局计算**。整块可省 = 不变换。
 *
 * ## ⚠️ 它和 `rect` 的分工，是这份契约里最要命的一条
 *
 * | | 参与布局计算吗 |
 * |---|---|
 * | `rect` | **参与** —— 对齐、间距、网格、溢出检测全靠它 |
 * | `transform` | **不参与** —— 只转画面，别的什么都不动 |
 *
 * 所以**它们被分成两个字段，而不是合成一个**：
 * 一个转过（或斜切过）的矩形**没有「边」**、只剩角点，
 * 「左边缘对齐」这类说法本身就退化了。合成一个对象会抹掉这条线，
 * 让人以为"变换也是布局的一部分"。
 *
 * 以后的缩放、镜像同样归这里，`rect` 保持纯布局。
 */
export interface Transform {
  /**
   * 旋转角度（**度，顺时针为正**）。
   * 允许小数与负值（`-22` = 逆时针 22°）。省略 = 不转。
   */
  rotate?: number;
  /**
   * **水平斜切**：顶边相对底边水平偏移的比例（相对框宽）。
   * `0.15` = 顶边向右错开 15%；负值向左。省略 = 不斜切。
   *
   * ⚠️ 斜切是**变换**，不是一种「形状」——因为它会改变包围盒（和旋转同理），
   * 所以不能参与布局计算。做斜切图块时用 `shape: "rect"` + 这个字段，
   * 而不是去找一个"平行四边形"形状。
   */
  skewX?: number;
  /**
   * 变换的**支点**：相对 **`rect` 自身**的 0–1 坐标。
   * 省略 = 中心（`{ x: 0.5, y: 0.5 }`）。
   *
   * 常用值：中心 `0.5 0.5` · 左上角 `0 0` · 左下角 `0 1` · 上边中点 `0.5 0`。
   * 等价于 CSS 的 `transform-origin`。
   *
   * ⚠️ 它单独出现没有意义——必须配合 `rotate` 或 `skewX`。
   */
  origin?: { x: number; y: number };
}

/** 三类节点共有的字段 */
export interface NodeBase {
  /**
   * 稳定标识，落成 HTML 的 `data-layer`。
   * 拆层与文字自适应都靠它定位，所以**改版式时不要动已有 id**。
   */
  id: string;
  /** 放在哪、占多大。**参与**对齐 / 间距 / 网格计算 */
  rect: Rect;
  /** 人读的说明。草图上的区域标签显示它，所以写清楚"这里是什么" */
  name?: string;
  /** 视觉变换（旋转…）。省略 = 不动它 —— 见上面 `Transform` */
  transform?: Transform;
}

/**
 * 图 —— 照片、场景、商品图、图标。
 *
 * 主体由生图阶段负责画出来；这里只声明**给它留了多大的位置**。
 */
export interface ImageNode extends NodeBase {
  type: 'image';
  /**
   * 素材**文件名**（如 `bottle.png`）。
   * 它由 `asset-order.json` 的订单生产——这里只写名字，不做映射。
   */
  asset: string;
  /**
   * 图怎么装进位置。
   * - `cover`（默认）：铺满，超出部分裁掉——场景照用
   * - `contain`：完整放进，可能留空——**商品图用**（不能裁到主体）
   */
  fit?: 'cover' | 'contain';
}

/**
 * 文字 —— 要出现在画面上的文案。
 *
 * ⚠️ **只放真正会显示的字**。「斜光」「磨砂质感」这类**效果描述**不是文案，
 * 它们归生图提示词，不要写成文字节点。
 */
export interface TextNode extends NodeBase {
  type: 'text';
  /** 一行用字符串，多行用字符串数组 */
  text: string | string[];
  /**
   * 字号：**相对画布宽度**的比例。
   * 主标题约 0.045–0.055、副标题 0.024–0.030、脚注 0.014–0.019。
   * （字号是版式属性——它决定文字块占多大。）
   */
  fontScale?: number;
  /** 字重。省略用排版方案的正文字重 */
  weight?: number;
  /** 对齐方式。省略 left */
  align?: 'left' | 'center' | 'right';
}

/**
 * 形状 —— 框 / 底板 / 分区，**三合一**。
 *
 * 它是**独立的元素**，不是别的节点的属性：
 * - 想"框住一张图"？放一个形状节点，让它和那张图**位置重叠**
 * - 描边不填充 = 框；填充不描边 = 底板（具体颜色归外观文件）
 *
 * ⚠️ **它自己给自己尺寸**，不依赖任何内容——所以它可以是
 * "一个比文字大得多的大圆"，也可以和内容严丝合缝。
 */
export interface ShapeNode extends NodeBase {
  type: 'shape';
  /** 是什么形状 */
  shape: Shape;
  /**
   * 圆角：**相对框短边**的比例（0–1）。**仅 `rect` 有效**。
   * `0` = 直角（省略时的默认）；`0.5` = 完全变成胶囊。
   *
   * 用比例而非像素，是为了跟着框一起缩放——换画布尺寸时观感不变。
   */
  radius?: number;
}

export type Node = ImageNode | TextNode | ShapeNode;

/**
 * 全部节点类型。
 *
 * ⚠️ 这是**唯一的类型清单**——`NodeType` 从它推导，
 * 不再手写第二份（旧契约里 `LAYER_TYPES` 和 `Layer` 联合各写一遍，
 * 必然漂移，文档里曾因此出现不存在的类型名）。
 */
export const NODE_TYPES = ['image', 'text', 'shape'] as const;
export type NodeType = (typeof NODE_TYPES)[number];

// ══════════════════════════════════════════════════════════════════════
// 顶层
// ══════════════════════════════════════════════════════════════════════

export interface DesignSketch {
  /** 名称（英文/数字/连字符）。决定产物目录 `test_product/layout/<name>/` */
  name: string;
  /** 人读标题，写进溯源注释 */
  title?: string;
  /** 这份版式在讲什么（可选，写进溯源） */
  description?: string;

  canvas: Canvas;

  /**
   * 节点，**有序**——数组顺序即叠放顺序（先写的在下面）。
   * 每个节点落成一个带 `data-layer` 的容器。
   *
   * ⚠️ 「谁框住谁」也靠这个顺序表达：形状写在图的**前面**就在图下面、
   * 起"底板"作用；写在**后面**就压在图上面、起"相框"作用。
   */
  layers: Node[];
}
