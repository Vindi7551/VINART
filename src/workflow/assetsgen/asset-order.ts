/**
 * AssetOrder —— 素材订单（生图请求的契约）
 *
 * 一份订单 = 一次生图请求：要生成什么文件、用什么提示词、拿哪几张图当参考。
 *
 * 📖 职责边界与完整说明见同目录 `README.md`。
 *
 * ⚠️ 四条硬约束（内核已封装，不要在各处重复处理）：
 *   · 参考图**不设硬上限**（方舟 ≤14 张；每张是 data URL，注意请求体大小）
 *   · 输出尺寸**下限 3,686,400 像素**（约 1920²；竖构图用 1440x2560）
 *   · 提示词**避免品牌 / 水印类词汇** —— 实测会触发内容审核
 *     （讽刺的是"禁止品牌标识"这条指令本身就会触发）。
 *     共享禁词表见 `BANNED_WORDS`——审核器共性与提示词语言无关。
 *   · 审核是**概率性**的，同一份输入时过时不过 → 内核负责重试
 */

/**
 * 审核禁词表——多语言合并检查（词形互不冲突，一次全查）。
 * 实测德语 Logos / Marken / Wasserzeichen 触发内容审核；英文 / 中文
 * 等价词同样是审核器高危区。订单生成（order.ts）与运行时（image.ts）
 * 共用这一份，保证两道关同源。
 */
export const BANNED_WORDS =
  /\blogos?\b|\bwatermarks?\b|\bbrand( |-)?marks?\b|logos|marken|wasserzeichen|水印|品牌标识/gi;

/**
 * 参考图**就是文件名**，没有角色字段：
 * - 相对**版式目录**：`'detail.png'`
 * - 相对**工作目录**：`'uploads/chat-xxxx.png'`（用户贴的商品照）
 * - 绝对路径也可以，但必须落在工作目录里
 *
 * ⚠️ 哪张图是干什么的，由**提示词自己说**（如「[图片1] 是商品照，外观必须一致」）——
 * 不再有 role 字段、也不由内核猜。提示词里的 `[图片N]` 会在发送前编译成
 * 「第 N 张（文件名）」；参考图说明只负责把没被点名的「第 N 张 ↔ 文件名」对上。
 */

/** 一次素材生成请求 */
export interface AssetRequest {
  /**
   * 输出**文件名**，如 `scene.png`。
   * `layers[].asset` 用**同一个字符串**引用它——直接拿文件名当引用，
   * 不做 id→文件名的映射，少一层出错的地方。
   */
  file: string;
  /** 输出尺寸，如 `2048x2048` / `1440x2560` */
  size: string;
  /**
   * 生成提示词。**语言不限**——由调用方决定；
   * 若订单由模型生成，提示词语言是那次生成的一个输入项（不是这里的固定值）。
   * 画面里需要什么语言的文字，由 brief 决定并最终由 HTML 渲染——
   * 生图模型不画字，所以提示词语言与目标市场**没有必然关系**。
   *
   * ## 写法规范——按七要素组织，完整自然语言句子
   *
   * 当前接入的生图模型（seedream）是**指令型**：理解完整句子，不认识标签权重。
   *
   * 1. **主体**——是什么（可带需要模型注意的细节）
   * 2. **动作与状态**
   * 3. **场景**——发生在哪里
   * 4. **风格与媒介**——什么质感的照片（如：商业产品摄影 / Kodak Portra 400 胶片）
   * 5. **光线与色调**——光源方向与色温（如：左侧柔光箱 / 暖钨丝灯＋冷蓝阴影）
   * 6. **构图·镜头**——怎么拍（如：45° 俯视 / 85mm f/1.4 / 浅景深 / 留白）
   * 7. **技术参数**——画幅与分辨率。**不写进 prompt**：size 是订单的独立字段
   *
   * ⚠️ 指令型模型的三条禁则（image.ts 有 warn 检查）：
   * - 权重语法 `(red dress:1.4)` / `marble::2` **无效**——用「以…为主」的表述
   * - 质量词堆砌（masterpiece / best quality / 8k）**有害无益**
   * - 负向词**不需要**（那是标签权重型的常规手段，指令型不认）
   *
   * （若将来接入 Midjourney / SD1.5 / SDXL 这类**标签权重型**模型，
   * 以上规范反过来——订单生成要按该模型的方言重写。）
   *
   * ## 保真声明（有参考图时）
   *
   * 引用商品实物照的订单，提示词里应有**保真声明**——否则模型会
   * 擅自改 logo、增删部件，成品与实物不符。典型句式：
   *   "keep the shape, lid, label and color exactly the same,
   *    do not add extra text or graphics"
   * （image.ts 对有参考图却缺保真表述的订单给 warn）
   *
   * 声明的**具体措辞按行业由 brief 指定**，这里只提供机制——不绑定某个行业。
   */
  prompt: string;
  /**
   * 生成提示词的**语言代码**（en / de / zh …），整份订单统一一个值。
   *
   * ⚠️ 提示词的读者是**生图模型**，不是终端消费者——seedream 中英双语原生
   * （官方文档：所有模型支持中英文；德语等是 5.0 额外支持的语言），
   * 所以默认 `en`。与 listing 的市场语言**无关**，不要把市场语言搬进来。
   *
   * 订单自包含这个字段：gen 阶段拼参考图说明时用它兜底
   * （提示词含中文时直接用中文，不看它）。
   */
  promptLang?: string;
  /** 参考图文件名（最多 14 张；不设更小的硬上限） */
  references?: string[];
}

/** 一个版式需要生成的全部素材 */
export type AssetOrders = AssetRequest[];
